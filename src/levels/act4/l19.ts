/** Every 10 minutes from 04:00 until "now": one CRON line per run. */
const RUNS = (NOW - FIRST_RUN) / 600_000;

const VIXIE = '# (Cron version -- $Id: crontab.c,v 2.13 1994/01/17 03:20:37 vixie Exp $)';
/** Header crontab(1) writes: "(- installed" means the job came from a pipe, not from an editor. */
const userCrontab = (source: string, installed: string, body: string) =>
  `# DO NOT EDIT THIS FILE - edit the master and reinstall.\n# (${source} installed on ${installed})\n${VIXIE}\n${body}\n`;

function syslog(): string {
  const rand = seeded(1919);
  let pid = 30211;
  const lines: [number, string][] = [];
  const line = (at: number, text: string) => lines.push([at, `${syslogTime(new Date(at))} ${ACT4.dbHost} ${text}`]);
  const cron = (at: number, user: string, command: string) => {
    pid += 1 + Math.floor(rand() * 40);
    line(at, `CRON[${pid}]: (${user}) CMD (${command})`);
  };
  for (let t = FROM; t < NOW; t += 60_000) {
    const minute = new Date(t).getUTCMinutes();
    const hour = new Date(t).getUTCHours();
    const at = t + 1000;
    if (minute % 10 === 5) cron(at, 'root', 'command -v debian-sa1 > /dev/null && debian-sa1 1 1');
    if (minute === 17) cron(at, 'root', 'cd / && run-parts --report /etc/cron.hourly');
    if (minute === 0 && hour % 12 === 0) cron(at, 'root', 'test -x /usr/bin/certbot && certbot -q renew');
    if (minute === 30 && hour === 1) cron(at, 'postgres', '/usr/local/bin/pg-nightly.sh');
    if (minute === 25 && hour === 6) cron(at, 'root', 'test -x /usr/sbin/anacron || { cd / && run-parts --report /etc/cron.daily; }');
    if (t >= FIRST_RUN && minute % 10 === 0) cron(at, ACT4.secondAccount, BEACON);
  }
  for (const day of ['13', '14']) {
    line(Date.parse(`2026-03-${day}T00:00:02Z`), 'systemd[1]: Starting logrotate.service - Rotate log files...');
    line(Date.parse(`2026-03-${day}T00:00:03Z`), 'systemd[1]: logrotate.service: Deactivated successfully.');
    line(Date.parse(`2026-03-${day}T06:12:44Z`), 'systemd[1]: Starting apt-daily.service - Daily apt download activities...');
    line(Date.parse(`2026-03-${day}T06:12:51Z`), 'systemd[1]: apt-daily.service: Deactivated successfully.');
  }
  line(Date.parse(ACT4.cronAt), `crontab[2291]: (${ACT4.secondAccount}) REPLACE (${ACT4.secondAccount})`);
  line(Date.parse('2026-03-13T03:51:01Z'), `cron[611]: (${ACT4.secondAccount}) RELOAD (crontabs/${ACT4.secondAccount})`);
  return `${lines.sort((a, b) => a[0] - b[0]).map(([, text]) => text).join('\n')}\n`;
}

