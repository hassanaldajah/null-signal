function sessions(): string {
  const rows: [string, string][] = [];
  for (let day = 1; day <= 14; day++) {
    const at = `2026-03-${String(day).padStart(2, '0')}T01:58:${String(10 + day).padStart(2, '0')}Z`;
    rows.push([at, `${at} session start user=${ACT6.pullAccount} src=${ACT6.vendorIp} duration=6m`]);
  }
  for (const [at, minutes] of NOVA_SESSIONS) rows.push([at, `${at} session start user=${ACT6.vendorAccount} src=${ACT6.vendorIp} duration=${minutes}m`]);
  return `${rows.sort(([a], [b]) => a.localeCompare(b)).map(([, line]) => line).join('\n')}\n`;
}

